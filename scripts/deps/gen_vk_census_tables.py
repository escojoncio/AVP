#!/usr/bin/env python3
"""Generates klepton/runtime/gfx/kl_vk_census_tables.h from the Khronos registry (vk.xml).

The Vulkan census (KL_VK_CENSUS, kl_vk_census.inc) decodes every feature struct a guest chains
into VkDeviceCreateInfo / VkPhysicalDeviceFeatures2 and names every pNext sType it meets. This
writes those tables: for each struct that extends VkPhysicalDeviceFeatures2 or VkDeviceCreateInfo,
its sType, its name, and the offset and name of each VkBool32 member, guarded by the core
version or extension macro that declares it (so it compiles against older headers too).

Usage: gen_vk_census_tables.py <Vulkan-Headers>/registry/vk.xml <out.h>
"""
import sys
import xml.etree.ElementTree as ET

reg = ET.parse(sys.argv[1]).getroot()
structs = {}
aliases = set()
for t in reg.iter('type'):
    if t.get('category') != 'struct':
        continue
    if t.get('alias'):
        aliases.add(t.get('name'))
        continue
    structs[t.get('name')] = t

# Which core version or extension first declares each type (its #ifdef guard).
guard = {}
for f in reg.findall('feature'):
    # Newer registries split each core version into VK_BASE_/VK_COMPUTE_/VK_GRAPHICS_VERSION_1_x
    # blocks, which headers do not define as macros: every one guards on VK_VERSION_1_x.
    if 'vulkan' not in (f.get('api') or 'vulkan').split(','):
        continue
    fname = f.get('name')
    if not fname.startswith('VK_'):
        continue
    ver = 'VK_VERSION_' + fname.split('VERSION_', 1)[1] if 'VERSION_' in fname else fname
    for req in f.findall('require'):
        for ty in req.findall('type'):
            guard.setdefault(ty.get('name'), ver)
for e in reg.find('extensions').findall('extension'):
    if e.get('supported') in ('disabled',) or 'vulkan' not in (e.get('supported') or 'vulkan').split(','):
        continue
    if e.get('platform') or e.get('provisional') == 'true':
        continue
    for req in e.findall('require'):
        if req.get('api') and 'vulkan' not in req.get('api').split(','):
            continue
        for ty in req.findall('type'):
            guard.setdefault(ty.get('name'), e.get('name'))

def members(t):
    out = []
    for m in t.findall('member'):
        if m.get('api') and 'vulkan' not in m.get('api').split(','):
            continue
        ty = m.find('type').text
        nm = m.find('name').text
        out.append((ty, nm, m.get('values'), ''.join(m.itertext())))
    return out

rows = []
for name, t in sorted(structs.items()):
    ext = (t.get('structextends') or '').split(',')
    if 'VkPhysicalDeviceFeatures2' not in ext and 'VkDeviceCreateInfo' not in ext:
        continue
    g = guard.get(name)
    if not g:
        continue
    # Core versions, and the cross-vendor KHR/EXT extensions: a vendor extension's struct can postdate the
    # extension macro in older headers (the drivers' headers lag the registry), and none matter for VPEngine.
    if not (g.startswith('VK_VERSION_') or g.startswith('VK_KHR_') or g.startswith('VK_EXT_')):
        continue
    ms = members(t)
    stype = next((v for ty, nm, v, _ in ms if nm == 'sType'), None)
    if not stype:
        continue
    bools = [nm for ty, nm, v, full in ms if ty == 'VkBool32' and '[' not in full]
    rows.append((g, name, stype, bools))

base = structs['VkPhysicalDeviceFeatures']
base_bools = [nm for ty, nm, v, full in members(base) if ty == 'VkBool32']

o = []
o.append('// GENERATED by scripts/deps/gen_vk_census_tables.py from the Khronos registry (vk.xml) - do not edit.')
o.append('// The Vulkan census tables (kl_vk_census.inc): VkPhysicalDeviceFeatures\'s booleans, and every struct that')
o.append('// extends VkPhysicalDeviceFeatures2 or VkDeviceCreateInfo with its sType and its VkBool32 members.')
o.append('// Each row is guarded by the macro of the core version or extension that declares it.')
o.append('#pragma once')
o.append('typedef struct { unsigned short off; const char *name; } klc_bool;')
o.append('typedef struct { VkStructureType stype; const char *name; const klc_bool *bools; unsigned nbools; } klc_struct;')
o.append('static const klc_bool klc_base_features[] = {')
for b in base_bools:
    o.append(f'    {{ (unsigned short)offsetof(VkPhysicalDeviceFeatures, {b}), "{b}" }},')
o.append('};')
for g, name, stype, bools in rows:
    if not bools:
        continue
    o.append(f'#ifdef {g}')
    o.append(f'static const klc_bool klc_b_{name}[] = {{')
    for b in bools:
        o.append(f'    {{ (unsigned short)offsetof({name}, {b}), "{b}" }},')
    o.append('};')
    o.append('#endif')
o.append('static const klc_struct klc_structs[] = {')
for g, name, stype, bools in rows:
    o.append(f'#ifdef {g}')
    if bools:
        o.append(f'    {{ {stype}, "{name}", klc_b_{name}, {len(bools)} }},')
    else:
        o.append(f'    {{ {stype}, "{name}", 0, 0 }},')
    o.append('#endif')
o.append('    { (VkStructureType)0, 0, 0, 0 }')
o.append('};')
open(sys.argv[2], 'w').write('\n'.join(o) + '\n')
print(f'{len(rows)} structs, {sum(len(r[3]) for r in rows)} booleans')
