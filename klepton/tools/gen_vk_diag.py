#!/usr/bin/env python3
"""Generate runtime/gfx/kl_vk_diag_gen.h: the result-checking thunks of kl_vk_diag.inc.

    python3 tools/gen_vk_diag.py OUT.h vulkan_core.h [vulkan_android.h vulkan_xlib.h ...]

Every non-vkCmd Vulkan command found in the given headers gets two thunk variants
(two distinct real pointers per name) that call through and report to kl_vk_diag.inc:
VkResult commands are result-checked, every one is recorded in the call ring.

The thunks are written with ABI-primitive parameter types (void *, uint64_t, uint32_t,
int32_t, float), never with the header's own types. That makes the generated file
independent of the Vulkan header version Klepton is compiled against (MoltenVK's
vendored headers may be older or newer than the ones this ran over): a command the
build's headers do not know costs nothing, it is matched by name only. AArch64 passes
every Vulkan parameter type exactly like its primitive (handles and pointers in x
registers, 32-bit enums/flags/VkBool32 as 32-bit ints, floats in s registers, with
the same size and alignment on the stack), so a thunk forwards the guest's call
bit-for-bit. A by-value struct parameter would break that; the generator refuses one.
"""
import re
import sys

SKIP = {"vkGetInstanceProcAddr", "vkGetDeviceProcAddr"}   # Klepton serves these itself
PRIM = {
    "void": "void", "uint32_t": "uint32_t", "int32_t": "int32_t", "uint64_t": "uint64_t",
    "int64_t": "int64_t", "size_t": "size_t", "float": "float", "int": "int32_t",
    "uint16_t": "uint32_t", "uint8_t": "uint32_t",
    # platform scalars (Xlib/XCB/xrandr)
    "Window": "uint64_t", "VisualID": "uint64_t", "RROutput": "uint64_t",
    "xcb_window_t": "uint32_t", "xcb_visualid_t": "uint32_t",
}


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", " ", s, flags=re.S)
    return re.sub(r"//[^\n]*", " ", s)


def main():
    outpath, headers = sys.argv[1], sys.argv[2:]
    text = ""
    for h in headers:
        with open(h) as f:
            text += strip_comments(f.read()) + "\n"
    ver = re.search(r"#define\s+VK_HEADER_VERSION\s+(\d+)", text)

    disp = set(re.findall(r"^\s*VK_DEFINE_HANDLE\((\w+)\)", text, re.M))
    nondisp = set(re.findall(r"^\s*VK_DEFINE_NON_DISPATCHABLE_HANDLE\((\w+)\)", text, re.M))
    enums = set(re.findall(r"typedef\s+enum\s+(\w+)", text))
    structs = set(re.findall(r"typedef\s+(?:struct|union)\s+(\w+)\s*\{", text))
    alias = {}
    for a, b in re.findall(r"typedef\s+(\w+)\s+(\w+)\s*;", text):
        alias[b] = a

    def resolve(t):
        seen = 0
        while t in alias and seen < 16:
            t = alias[t]; seen += 1
        return t

    def classify(t):
        r = resolve(t)
        if r in disp: return "void *", "dhandle"
        if r in nondisp: return "uint64_t", "handle"
        if r in enums: return "int32_t", "scalar"
        if r == "VkFlags64": return "uint64_t", "scalar"
        if r in PRIM: return PRIM[r], ("void" if r == "void" else "scalar")
        if r in structs: raise SystemExit(f"by-value struct parameter {t} — cannot thunk")
        raise SystemExit(f"unknown type {t} (resolved {r})")

    results = re.findall(r"^\s*(VK_\w+)\s*=\s*(-?\d+)\s*,", text[text.find("typedef enum VkResult"):
                         text.find("} VkResult;")], re.M)

    protos = re.findall(r"VKAPI_ATTR\s+([\w ]+?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\)\s*;", text, re.S)
    cmds = {}
    for ret, name, params in protos:
        if name in SKIP or name.startswith("vkCmd") or name in cmds:
            continue
        ret = ret.strip()
        if ret == "PFN_vkVoidFunction":
            continue
        ps = []
        for p in [x.strip() for x in params.split(",")]:
            if p == "void" or not p:
                continue
            p = re.sub(r"\s+", " ", p)
            m = re.match(r"^(const )?(struct )?(\w+)\s*((?:\*\s*(?:const\s*)?)*)\s*(\w+)\s*(\[\w+\])?$", p)
            if not m:
                raise SystemExit(f"cannot parse param '{p}' of {name}")
            const, _, base, stars, pname, arr = m.groups()
            nstar = stars.count("*") + (1 if arr else 0)
            if nstar:
                ps.append(dict(c="void *", name=pname, kind="ptr", base=resolve(base),
                               const=bool(const), nstar=nstar))
            else:
                c, k = classify(base)
                ps.append(dict(c=c, name=pname, kind=k, base=resolve(base)))
        if ret == "VkResult":
            rc, rk = "VkResult", "result"
        else:
            rc, rk = classify(ret)
            if rk == "dhandle": rc = "void *"
        cmds[name] = dict(ret=rc, rk=rk, ps=ps)

    names = sorted(cmds)
    o = []
    w = o.append
    w("// GENERATED by tools/gen_vk_diag.py from Vulkan headers v%s — do not edit by hand.\n"
      % (ver.group(1) if ver else "?"))
    w("// Included twice by kl_vk_diag.inc: KLD_GEN_TABLE (names) then KLD_GEN_THUNKS.\n")
    w("#if defined(KLD_GEN_TABLE)\n")
    w("#define KLD_N %d\n" % len(names))
    w("static const char *const kld_names[KLD_N] = {\n")
    for n in names:
        w('    "%s",\n' % n)
    w("};\n")
    w("// 0 = no result checked (void / scalar return), 1 = VkResult\n")
    w("static const uint8_t kld_is_result[KLD_N] = {\n    ")
    w(",".join("1" if cmds[n]["rk"] == "result" else "0" for n in names))
    w("\n};\n")
    w("static const char *kld_result_name(int32_t r) {\n    switch (r) {\n")
    seen = set()
    for rn, rv in results:
        if rv in seen: continue
        seen.add(rv)
        w("    case %s: return \"%s\";\n" % (rv, rn))
    w("    default: return NULL;\n    }\n}\n")
    w("#elif defined(KLD_GEN_THUNKS)\n")

    for i, n in enumerate(names):
        c = cmds[n]
        ps = c["ps"]
        sig = ", ".join("%s a%d" % (p["c"], j) for j, p in enumerate(ps)) or "void"
        args = ", ".join("a%d" % j for j in range(len(ps)))
        ptype = ", ".join(p["c"] for p in ps) or "void"
        # first 32-bit scalar after the leading handle: VkFormat of a format query, etc.
        arg = "0"
        for j, p in enumerate(ps[1:3], 1):
            if p["kind"] == "scalar" and p["c"] in ("int32_t", "uint32_t"):
                arg = "(uint32_t)a%d" % j
                break
        # created handles: vkCreate*/vkAllocate*/vkGetDeviceQueue*, last param a non-const handle*
        out = None
        if re.match(r"^vk(Create|Allocate|GetDeviceQueue)", n) and ps:
            last = ps[-1]
            if (last["kind"] == "ptr" and not last["const"] and last["nstar"] == 1 and
                    (last["base"] in disp or last["base"] in nondisp)):
                cnt = "1u"
                for j, p in enumerate(ps):
                    if p["name"] in ("createInfoCount", "swapchainCount"):
                        cnt = "a%d" % j
                if n == "vkAllocateCommandBuffers":
                    cnt = "(a1 ? ((const VkCommandBufferAllocateInfo *)a1)->commandBufferCount : 0u)"
                if n == "vkAllocateDescriptorSets":
                    cnt = "(a1 ? ((const VkDescriptorSetAllocateInfo *)a1)->descriptorSetCount : 0u)"
                out = ("a%d" % (len(ps) - 1), cnt)
        for v in (0, 1):
            w("static %s VKAPI_CALL kld_%d_%d(%s) {\n" % (c["ret"], i, v, sig))
            w("    const void *ra = __builtin_return_address(0), *prev = kld_enter(ra);\n")
            call = "((%s (VKAPI_PTR *)(%s))kld_real_fn(%d, %d))(%s)" % (c["ret"], ptype, i, v, args)
            if c["rk"] == "void":
                w("    %s;\n" % call)
                w("    kld_leave(prev);\n")
                res, val = "KLD_NORES", "0"
            else:
                w("    %s r = %s;\n" % (c["ret"], call))
                w("    kld_leave(prev);\n")
                if c["rk"] == "result":
                    res, val = "(int32_t)r", "0"
                else:
                    res, val = "KLD_NORES", "(uint64_t)(uintptr_t)r"
            if out:
                cond = "r == VK_SUCCESS" if c["rk"] == "result" else "1"
                w("    uint64_t h = (%s) ? kld_out_handles(%d, ra, %s, %s) : 0;\n" % (cond, i, out[0], out[1]))
                val = "h"
            w("    kld_after(%d, %s, ra, %s, %s);\n" % (i, res, arg, val))
            if c["rk"] != "void":
                w("    return r;\n")
            w("}\n")
    w("static const PFN_vkVoidFunction kld_thunks[KLD_N][2] = {\n")
    for i, n in enumerate(names):
        w("    { (PFN_vkVoidFunction)kld_%d_0, (PFN_vkVoidFunction)kld_%d_1 },\n" % (i, i))
    w("};\n#endif\n")
    with open(outpath, "w") as f:
        f.write("".join(o))
    nres = sum(1 for n in names if cmds[n]["rk"] == "result")
    print(f"{len(names)} commands ({nres} VkResult) -> {outpath}")


if __name__ == "__main__":
    main()
